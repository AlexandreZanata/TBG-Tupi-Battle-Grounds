#!/usr/bin/env python3
"""Derive the public champion and Arena catalogs from the game's own sources.

The web frontends never decide game content: names come from the client
i18n files, Faction/Archetype from the tbg-core content table, the active
roster from FULL_POOL and Arena modifiers from the client Arena data that a
Rust test pins to tbg-core (GAME-DESIGN §11-§12). The generated JSON is
committed so previews and deploys need no build step; `--check` fails when
it drifts from the sources.
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CORE = REPO / "crates/tbg-core/src"
ASSETS = REPO / "crates/tbg-client/assets"
OUT = REPO / "web/landing/data"
LANGS = ("en", "pt-BR")
FACTIONS = ("Humans", "Undead", "Machines", "Plants", "Monsters", "Celestials", "Insects")
ARCHETYPES = ("Tank", "Dps", "Support", "Ranged", "Control")


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def load_i18n():
    return {lang: json.loads((ASSETS / f"i18n/{lang}.json").read_text()) for lang in LANGS}


def text(i18n, key):
    missing = [lang for lang in LANGS if key not in i18n[lang]]
    if missing:
        raise SystemExit(f"missing i18n key {key!r} for {missing}")
    return {lang: i18n[lang][key] for lang in LANGS}


def full_pool():
    src = (CORE / "types.rs").read_text()
    block = re.search(r"pub const FULL_POOL: \[UnitKind; (\d+)\] = \[(.*?)\];", src, re.S)
    kinds = re.findall(r"UnitKind::(\w+)", block.group(2))
    if len(kinds) != int(block.group(1)):
        raise SystemExit("FULL_POOL length does not match its declaration")
    return kinds


def unit_table():
    src = (CORE / "content.rs").read_text()
    rows = re.findall(r"unit\(UnitKind::(\w+),\s*\"[^\"]+\",\s*(\w+),\s*(\w+),", src)
    return {kind: (faction, archetype) for kind, faction, archetype in rows}


def champions(i18n):
    table = unit_table()
    out = []
    for kind in full_pool():
        faction, archetype = table[kind]
        portrait = f"media/portraits/{kind.lower()}.webp"
        if not (ASSETS / "battle/portraits" / f"{kind.lower()}.webp").is_file():
            raise SystemExit(f"no portrait for {kind}")
        out.append({
            "id": kind.lower(),
            "name": text(i18n, f"unit.{snake(kind)}.name"),
            "faction": faction.lower(),
            "archetype": archetype.lower(),
            "portrait": portrait,
        })
    return {
        "schema": 1,
        "source": "tbg-core FULL_POOL + content table; client i18n names (generated by web/scripts/sync_content.py)",
        "factions": [{"id": f.lower(), "name": text(i18n, f"faction.{f.lower()}")} for f in FACTIONS],
        "archetypes": [{"id": a.lower(), "name": text(i18n, f"archetype.{a.lower()}")} for a in ARCHETYPES],
        "champions": out,
    }


def signed(bp):
    # Typographic minus, like the browser Arenas page; values are whole or 2-decimal percents.
    value = f"{abs(bp) / 100:g}"
    return ("+" if bp > 0 else "−") + value + "%"


def arena_effects(i18n, arena, energy_scale):
    effects = []
    for field, key in (("moveBp", "move"), ("attackBp", "attack"), ("regenBp", "regen")):
        if arena[field]:
            template = text(i18n, f"arenas.effect.{key}")
            effects.append({lang: template[lang].replace("{value}", signed(arena[field])) for lang in LANGS})
    if arena["firstEvolveDiscount"]:
        template = text(i18n, "arenas.effect.evolve")
        amount = f"{arena['firstEvolveDiscount'] / energy_scale:g}"
        effects.append({lang: template[lang].replace("{value}", amount) for lang in LANGS})
    return effects or [text(i18n, "arenas.effect.none")]


def arenas(i18n):
    data = json.loads((ASSETS / "arenas/arenas.json").read_text())
    core = re.findall(r"Arena::\w+ => \"(\w+)\"", (CORE / "types.rs").read_text())
    slugs = [a["slug"] for a in sorted(data["arenas"], key=lambda a: a["id"])]
    if slugs != core[: len(slugs)] or len(slugs) != 8:
        raise SystemExit(f"Arena order {slugs} differs from tbg-core {core}")
    out = []
    for arena in sorted(data["arenas"], key=lambda a: a["id"]):
        slug = arena["slug"]
        if not (ASSETS / "arenas" / arena["image"]).is_file():
            raise SystemExit(f"no preview for Arena {slug}")
        out.append({
            "id": arena["id"],
            "slug": slug,
            "image": f"media/arenas/{arena['image']}",
            "accent": arena["accent"],
            "name": text(i18n, f"arenas.{slug}.name"),
            "theme": text(i18n, f"arenas.{slug}.theme"),
            "effects": arena_effects(i18n, arena, data["energyScale"]),
        })
    return {
        "schema": 1,
        "source": "client arenas.json pinned to tbg-core (GAME-DESIGN §12); client i18n text (generated by web/scripts/sync_content.py)",
        "arenas": out,
    }


def render(doc):
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def generated():
    i18n = load_i18n()
    return {"champions.json": render(champions(i18n)), "arenas.json": render(arenas(i18n))}


def main_check():
    """0 when the committed catalogs equal a fresh derivation, else 1 (used by check.py too)."""
    stale = [name for name, body in generated().items()
             if not (OUT / name).is_file() or (OUT / name).read_text() != body]
    if stale:
        print("stale generated content (run web/scripts/sync_content.py):", *stale, sep="\n  ")
        return 1
    print("generated content up to date: " + ", ".join(generated()))
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed files are stale")
    if parser.parse_args().check:
        return main_check()
    OUT.mkdir(parents=True, exist_ok=True)
    for name, body in generated().items():
        (OUT / name).write_text(body)
    print("content written to", OUT.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
