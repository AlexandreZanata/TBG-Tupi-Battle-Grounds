//! Where each War Auxiliary precinct stands in an Arena, and the wooden bridge
//! that reaches it from the shore when its pad lies over the water.

use crate::arena::{geometry::outline, theme::Theme};
use bevy::prelude::*;
use tbg_core::{auxiliary::AuxiliaryKind, Seat};

/// World X centers for Left (`Seat::A` / Blue) and Right (`Seat::B` / Red) precincts.
pub(super) const LEFT_X: f32 = -2.55;
pub(super) const RIGHT_X: f32 = 18.55;
/// World Z center for the North/upper flank `Mineiro` precinct (`z < -2.67`).
pub(super) const MINE_Z: f32 = -3.45;
/// World Z center for the South/lower flank `Mercador` stall (`z > +2.67`).
pub(super) const MERCHANT_Z: f32 = 3.45;
/// Deck height of platforms and bridges, just above the meadow (`y = -0.04`).
pub(super) const DECK_Y: f32 = 0.0;
/// How far inland a bridge's first plank rests, so it never floats at the rim.
const LANDING: f32 = 0.45;

/// Precinct-local center (x, z) of the pad every tier is built on.
pub(super) const fn pad_center(kind: AuxiliaryKind) -> Vec2 {
    match kind {
        AuxiliaryKind::Miner => Vec2::new(0.1, 0.0),
        AuxiliaryKind::Merchant => Vec2::new(-0.25, -0.05),
    }
}

/// Precinct-local half extents (x, z) of that pad.
pub(super) const fn pad_half(kind: AuxiliaryKind) -> Vec2 {
    match kind {
        AuxiliaryKind::Miner => Vec2::new(1.0, 0.8),
        AuxiliaryKind::Merchant => Vec2::new(1.2, 0.5),
    }
}

/// Resolved layout of one precinct.
#[derive(Clone, Copy, Debug)]
pub(super) struct Placement {
    /// World transform; Seat B is mirrored along X so both face their Stronghold.
    pub root: Transform,
    /// True when the pad center lies outside the island outline.
    pub on_water: bool,
    /// Bridge from shore to pad edge, in precinct-local space at `DECK_Y`.
    pub bridge: Option<(Vec3, Vec3)>,
}

pub(super) fn mirror(seat: Seat) -> f32 {
    match seat {
        Seat::A => 1.0,
        Seat::B => -1.0,
    }
}

fn base_anchor(seat: Seat, kind: AuxiliaryKind) -> Vec2 {
    let x = match seat {
        Seat::A => LEFT_X,
        Seat::B => RIGHT_X,
    };
    let z = match kind {
        AuxiliaryKind::Miner => MINE_Z,
        AuxiliaryKind::Merchant => MERCHANT_Z,
    };
    Vec2::new(x, z)
}

/// Per-Arena layout of one seat's precincts: for `[Miner, Merchant]`, the
/// world offset from the base anchor and a yaw (radians) that turns the pad,
/// plus the Merchant ship's sea lane as a precinct-local heading (`0` = local
/// +X). Chosen by the `search_collision_free_layouts` lab so no tier, bridge or
/// ship course touches that Arena's existing scenery (BR-AX15).
#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) struct Layout {
    pub offsets: [Vec2; 2],
    pub yaws: [f32; 2],
    pub ship_heading: f32,
}

/// Default sea lane: the ship waits west of the pier, slightly offshore.
#[cfg(test)]
pub(super) const DEFAULT_HEADING: f32 = 2.95;

const fn layout_of(mine: [f32; 3], merchant: [f32; 3], ship_heading: f32) -> Layout {
    Layout {
        offsets: [
            Vec2::new(mine[0], mine[1]),
            Vec2::new(merchant[0], merchant[1]),
        ],
        yaws: [mine[2], merchant[2]],
        ship_heading,
    }
}

/// `[theme][seat]`, Themes in `Theme` declaration order; generated by
/// `search_collision_free_layouts` against each Arena's real scenery.
#[rustfmt::skip]
const LAYOUTS: [[Layout; 2]; 8] = [
    // Forest
    [layout_of([-1.75, 2.00, 0.00], [0.00, 0.25, 0.00], 2.880), layout_of([-0.50, -1.00, 0.00], [-0.50, 1.50, -0.50], 2.880)],
    // Tundra
    [layout_of([0.00, -1.00, 0.00], [-1.22, -2.34, -1.67], 1.571), layout_of([-0.75, -0.75, 0.00], [0.25, -0.25, 0.50], 2.618)],
    // Volcanic
    [layout_of([1.50, -0.25, 0.00], [4.55, 1.49, -0.27], 1.571), layout_of([-1.50, -0.25, 0.00], [1.45, -3.45, 1.57], 1.833)],
    // Ruins
    [layout_of([-0.50, -1.25, 0.00], [4.31, 1.68, 0.23], 2.618), layout_of([1.25, 0.50, 0.50], [0.00, 0.00, 0.50], 2.618)],
    // Storm
    [layout_of([-0.50, 0.00, 1.57], [3.88, 1.29, 0.19], 2.094), layout_of([-1.25, -1.00, 0.00], [0.00, 0.00, 0.50], 2.618)],
    // Celestial
    [layout_of([1.75, -1.25, 0.50], [4.31, 1.68, -0.27], 1.571), layout_of([1.75, 1.25, 0.00], [0.00, 0.00, 0.50], 2.618)],
    // Clockwork
    [layout_of([-1.75, 1.50, 0.50], [4.55, 1.49, -0.27], 1.571), layout_of([1.75, 1.25, 0.00], [0.00, 0.00, 0.50], 2.618)],
    // Desert
    [layout_of([1.50, -0.25, 0.00], [4.31, 1.68, -0.27], 1.571), layout_of([-1.50, -0.25, 0.00], [0.00, 0.00, 0.50], 2.618)],
];

pub(super) fn layout(theme: Theme, seat: Seat) -> Layout {
    LAYOUTS[theme as usize][seat.index()]
}

/// World XZ position and yaw of one precinct in an Arena.
pub(super) fn anchor(theme: Theme, seat: Seat, kind: AuxiliaryKind) -> (Vec2, f32) {
    let l = layout(theme, seat);
    let slot = usize::from(kind.slot());
    (base_anchor(seat, kind) + l.offsets[slot], l.yaws[slot])
}

#[cfg(test)]
pub(super) fn base(seat: Seat, kind: AuxiliaryKind) -> Vec2 {
    base_anchor(seat, kind)
}

pub(super) fn placement(theme: Theme, seat: Seat, kind: AuxiliaryKind) -> Placement {
    let (at, yaw) = anchor(theme, seat, kind);
    placement_at(seat, kind, at, yaw)
}

/// Shortest bridge worth drawing; a pad nearer the shore simply abuts it.
const MIN_BRIDGE: f32 = 0.35;

fn root_transform(seat: Seat, at: Vec2, yaw: f32) -> Transform {
    Transform::from_xyz(at.x, 0.0, at.y)
        .with_rotation(Quat::from_rotation_y(yaw))
        .with_scale(Vec3::new(mirror(seat), 1.0, 1.0))
}

pub(super) fn placement_at(seat: Seat, kind: AuxiliaryKind, at: Vec2, yaw: f32) -> Placement {
    let root = root_transform(seat, at, yaw);
    let rim: Vec<Vec2> = outline().iter().map(|p| p.xz()).collect();
    let on_water = !inside(&rim, at);
    let bridge = if on_water {
        bridge(&rim, kind, at, root)
    } else {
        None
    };
    Placement {
        root,
        on_water,
        bridge,
    }
}

fn bridge(rim: &[Vec2], kind: AuxiliaryKind, at: Vec2, root: Transform) -> Option<(Vec3, Vec3)> {
    let to_local = root.compute_affine().inverse();
    let shore = closest_on(rim, at);
    let dir = (shore - at).normalize_or_zero();
    let land = shore + dir * LANDING;
    let local_dir = to_local
        .transform_vector3(Vec3::new(dir.x, 0.0, dir.y))
        .xz()
        .normalize_or_zero();
    let (center, half) = (pad_center(kind), pad_half(kind));
    // Leave the pad through the side facing the shore.
    let t = (half.x / local_dir.x.abs().max(1e-4)).min(half.y / local_dir.y.abs().max(1e-4));
    let edge = center + local_dir * t;
    let edge = Vec3::new(edge.x, DECK_Y, edge.y);
    let land = to_local.transform_point3(Vec3::new(land.x, DECK_Y, land.y));
    // A pad whose edge already rests on land, or nearly does, needs no bridge.
    if inside(rim, root.transform_point(edge).xz()) || land.distance(edge) < MIN_BRIDGE {
        return None;
    }
    Some((land, edge))
}

/// Pier-end berth of the Merchant ship, precinct-local XZ.
/// Alongside the pier end (`z = 1.55`) with room for the tier-3 galleon's beam.
pub(super) const BERTH: Vec2 = Vec2::new(0.0, 1.98);

/// Ship position `distance` out along its sea lane from the berth.
pub(super) fn ship_point(heading: f32, distance: f32) -> Vec2 {
    BERTH + Vec2::new(heading.cos(), heading.sin()) * distance
}

/// Sea-surface decoration (ice floes, lily pads, lava crust) sits below this height.
pub(super) const FLOATER_Y: f32 = -1.0;
/// Half-width of the Merchant's sea lane, wide enough for the tier-3 galleon.
const LANE_HALF: f32 = 1.05;
const LANE_LENGTH: f32 = 3.0;

/// True when a floater centered at `p` with radius `r` would cross this
/// precinct's harbor zone: its pad, or for the Merchant its pier and sea lane.
pub(super) fn in_harbor(
    seat: Seat,
    kind: AuxiliaryKind,
    at: Vec2,
    yaw: f32,
    heading: f32,
    p: Vec2,
    r: f32,
) -> bool {
    let root = root_transform(seat, at, yaw);
    let local = root
        .compute_affine()
        .inverse()
        .transform_point3(Vec3::new(p.x, 0.0, p.y))
        .xz();
    let off = (local - pad_center(kind)).abs() - pad_half(kind);
    if off.max(Vec2::ZERO).length() <= r + 0.2 {
        return true;
    }
    if kind != AuxiliaryKind::Merchant {
        return false;
    }
    let (a, b) = (pad_center(kind), ship_point(heading, LANE_LENGTH));
    let (pier, berth) = (a, BERTH);
    [(pier, berth), (berth, b)].iter().any(|&(s, e)| {
        let t = ((local - s).dot(e - s) / (e - s).length_squared().max(1e-6)).clamp(0.0, 1.0);
        local.distance(s + (e - s) * t) <= LANE_HALF + r
    })
}

/// Runtime rule shared with the collision lab: a sea-surface prop at `p`
/// (radius `r`) is not placed where an auxiliary harbor needs open water.
pub(super) fn clears_floater(theme: Theme, p: Vec3, r: f32) -> bool {
    p.y < FLOATER_Y
        && Seat::BOTH.into_iter().any(|seat| {
            let heading = layout(theme, seat).ship_heading;
            AuxiliaryKind::ALL.into_iter().any(|kind| {
                let (at, yaw) = anchor(theme, seat, kind);
                in_harbor(seat, kind, at, yaw, heading, p.xz(), r)
            })
        })
}

/// Even-odd point-in-polygon test on the XZ plane.
fn inside(poly: &[Vec2], p: Vec2) -> bool {
    let mut hit = false;
    for (i, a) in poly.iter().enumerate() {
        let b = poly[(i + 1) % poly.len()];
        if (a.y > p.y) != (b.y > p.y) && p.x < a.x + (p.y - a.y) / (b.y - a.y) * (b.x - a.x) {
            hit = !hit;
        }
    }
    hit
}

fn closest_on(poly: &[Vec2], p: Vec2) -> Vec2 {
    poly.iter()
        .enumerate()
        .map(|(i, a)| {
            let b = poly[(i + 1) % poly.len()];
            let ab = b - *a;
            let t = ((p - *a).dot(ab) / ab.length_squared().max(1e-6)).clamp(0.0, 1.0);
            *a + ab * t
        })
        .min_by(|x, y| x.distance_squared(p).total_cmp(&y.distance_squared(p)))
        .unwrap_or(p)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn offshore_pads_get_a_bridge_that_lands_on_the_island() {
        let rim: Vec<Vec2> = outline().iter().map(|p| p.xz()).collect();
        for theme in tbg_core::Arena::ALL.map(Theme::from) {
            for seat in Seat::BOTH {
                for kind in AuxiliaryKind::ALL {
                    let p = placement(theme, seat, kind);
                    assert_eq!(p.on_water, !inside(&rim, anchor(theme, seat, kind).0));
                    let Some((land, edge)) = p.bridge else {
                        continue;
                    };
                    let world = p.root.transform_point(land).xz();
                    assert!(
                        inside(&rim, world),
                        "{theme:?} {seat:?} {kind:?} bridge lands in the sea"
                    );
                    let off = (edge.xz() - pad_center(kind)).abs();
                    let half = pad_half(kind);
                    assert!(off.x <= half.x + 1e-3 && off.y <= half.y + 1e-3);
                    assert!(
                        land.distance(edge) >= MIN_BRIDGE,
                        "{theme:?} {seat:?} {kind:?} bridge is visible"
                    );
                }
            }
        }
    }
}
